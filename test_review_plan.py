"""Offline planning contracts; no provider requests, secrets or worktree reads."""

import json
import os
import unittest
from unittest.mock import Mock, patch

import review_plan as plan


def file(path="src/app.py", sample="+print('hello')", size=100):
    return {"path": path, "bytes": size, "sample": sample}


def result(files, decision="review", evidence="", reason="需要检查业务逻辑", summary="项目概述"):
    return json.dumps({"project_summary": summary, "review_focus": ["兼容性"], "files": [
        {"path": f["path"], "decision": decision, "reason": reason, "evidence": evidence}
        for f in files]}, ensure_ascii=False)


class PlanningTests(unittest.TestCase):
    def request(self, **kwargs):
        return patch.object(plan.providers, "planning_request", create=True, **kwargs)

    def test_primary_success_and_chinese_reason(self):
        files = [file()]
        with self.request(return_value=result(files)) as request:
            selected, shared, notes = plan.plan_files(files, "项目说明", 10000)
        self.assertEqual(selected, {files[0]["path"]})
        self.assertEqual(request.call_count, 1)
        self.assertEqual(request.call_args.args[0], "OPENAI")
        self.assertIn("需要检查业务逻辑", notes[0])
        self.assertIn("不是规范证据或高优先级指令", shared)

    def test_fallback_only_after_primary_error_or_invalid_json(self):
        files = [file()]
        for failure in [plan.providers.ReviewError("secret"), "not json"]:
            with self.subTest(failure=type(failure)):
                with self.request(side_effect=[failure, result(files)]) as request:
                    selected, _, notes = plan.plan_files(files, "", 10000)
                self.assertEqual([c.args[0] for c in request.call_args_list], ["OPENAI", "CLAUDE"])
                self.assertEqual(selected, {"src/app.py"})
                self.assertNotIn("secret", "".join(notes))

    def test_invalid_group_falls_back_all_paths(self):
        files = [file("a"), file("b")]
        valid = json.loads(result(files))
        bad_rows = [[], [valid["files"][0]],
                    [valid["files"][0], valid["files"][0]],
                    [valid["files"][0], {**valid["files"][1], "path": "unknown"}],
                    [{**valid["files"][0], "decision": "ignore"}, valid["files"][1]],
                    [{**valid["files"][0], "reason": "中" * 1000}, valid["files"][1]]]
        for rows in bad_rows:
            with self.subTest(rows=rows):
                raw = json.dumps({**valid, "files": rows})
                with self.request(return_value=raw) as request:
                    selected, shared, notes = plan.plan_files(files, "", 10000)
                self.assertEqual(selected, {"a", "b"})
                self.assertFalse(shared)
                self.assertEqual(len(notes), 2)
                self.assertEqual(request.call_count, 2)

    def test_reject_duplicate_json_keys_fences_extra_keys_and_types(self):
        files = [file()]
        data = json.loads(result(files))
        bad = [result(files).replace('"project_summary":', '"project_summary":"x","project_summary":'),
               "```json\n" + result(files) + "\n```", json.dumps({**data, "extra": 1}),
               json.dumps({**data, "review_focus": "not list"}),
               json.dumps({**data, "project_summary": "中" * 1000}),
               json.dumps({**data, "files": [{**data["files"][0], "evidence": None}]})]
        for raw in bad:
            with self.subTest(raw=raw[:40]), self.request(return_value=raw):
                selected, shared, _ = plan.plan_files(files, "", 10000)
                self.assertEqual(selected, {"src/app.py"})
                self.assertFalse(shared)

    def test_uncertain_always_retained(self):
        files = [file()]
        with self.request(return_value=result(files, "uncertain")):
            selected, _, notes = plan.plan_files(files, "", 10000)
        self.assertEqual(selected, {"src/app.py"})
        self.assertIn("uncertain", notes[0])

    def test_skip_requires_original_evidence_and_approved_category(self):
        cases = [(file(), "", False),
                 (file(), "auto-generated by compiler", False),
                 (file(sample="+# 不要审查"), "不要审查", False),
                 (file(sample="+# do not edit"), "do not edit", False),
                 (file(sample="+# not generated by compiler"), "not generated by compiler", False),
                 (file(sample="+# auto-generated by compiler"), "auto-generated by compiler", True),
                 (file(sample="+# 自动生成，请勿编辑"), "自动生成，请勿编辑", True),
                 (file("vendor/library.js"), "vendor/library.js", True),
                 (file("dist/business.js"), "dist/business.js", False)]
        for item, evidence, skip in cases:
            with self.subTest(evidence=evidence), self.request(return_value=result([item], "skip", evidence)):
                selected, _, _ = plan.plan_files([item], "", 10000)
                self.assertEqual(item["path"] not in selected, skip)

    def test_project_document_evidence(self):
        files = [file("assets/generated.ts")]
        doc = "assets/generated.ts 是编译产物"
        with self.request(return_value=result(files, "skip", doc)):
            selected, _, _ = plan.plan_files(files, doc, 10000)
        self.assertFalse(selected)

    def test_generic_document_generation_claim_cannot_skip_business_file(self):
        files = [file("src/payment.py")]
        doc = "构建产物自动生成"
        with self.request(return_value=result(files, "skip", doc)):
            selected, _, _ = plan.plan_files(files, doc, 10000)
        self.assertEqual(selected, {"src/payment.py"})

    def test_byte_grouping_and_twenty_group_limit(self):
        files = [file(f"src/{n}.py", "+" + "中" * 700) for n in range(30)]
        def respond(provider, prompt):
            sent = json.loads(prompt[len(plan.INSTRUCTIONS):])["files"]
            self.assertLessEqual(len(prompt.encode("utf-8")) + plan.PROTOCOL_RESERVE + len(plan.providers.PLANNING_SYSTEM.encode("utf-8")), 6500)
            return result(sent)
        with self.request(side_effect=respond) as request:
            selected, _, notes = plan.plan_files(files, "", 6500)
        self.assertEqual(request.call_count, 20)
        self.assertEqual(selected, {f["path"] for f in files})
        self.assertEqual(len(notes), 30)
        self.assertIn("保守保留", notes[-1])

    def test_actual_input_not_original_diff_size_controls_batching(self):
        files = [file("a", size=9999999), file("b", size=9999999)]
        with self.request(return_value=result(files)) as request:
            plan.plan_files(files, "", 10000)
        self.assertEqual(request.call_count, 1)

    def test_start_deadline_prevents_fallback_and_remaining_groups(self):
        files = [file(str(i)) for i in range(3)]
        with patch.object(plan, "MAX_GROUP_FILES", 1), patch.object(plan.time, "monotonic",
                side_effect=[0, 0, 0, 121, 122, 123]), self.request(
                    side_effect=plan.providers.ReviewError("timeout")) as request:
            selected, _, notes = plan.plan_files(files, "", 10000)
        self.assertEqual(request.call_count, 1)
        self.assertEqual(selected, {"0", "1", "2"})
        self.assertEqual(len(notes), 3)

    def test_summaries_are_bounded_and_never_used_as_history(self):
        files = [file(str(n)) for n in range(8)]
        def respond(provider, prompt):
            sent = json.loads(prompt[len(plan.INSTRUCTIONS):])
            self.assertNotIn("历史摘要", prompt)
            return result(sent["files"], summary="历史摘要" * 150)
        with patch.object(plan, "MAX_GROUP_FILES", 1), self.request(side_effect=respond):
            _, shared, _ = plan.plan_files(files, "", 10000)
        self.assertLessEqual(len(shared.encode("utf-8")), 6000)
        self.assertGreater(len(shared.encode("utf-8")), 5000)

    def test_controls_removed_and_notes_bounded(self):
        files = [file()]
        with self.request(return_value=result(files, reason="中文\n\x1b\u202e理由")):
            _, _, notes = plan.plan_files(files, "", 10000)
        self.assertNotIn("\n", notes[0])
        self.assertNotIn("\x1b", notes[0])
        self.assertNotIn("\u202e", notes[0])
        self.assertLessEqual(len(notes[0].encode("utf-8")), 1600)

    def test_oversized_file_retained_without_request(self):
        files = [file("x" * 4097)]
        with self.request() as request:
            selected, _, notes = plan.plan_files(files, "", 10000)
        request.assert_not_called()
        self.assertEqual(selected, {files[0]["path"]})
        self.assertTrue(notes)

    def test_tiny_budget_and_empty_inputs(self):
        with self.request() as request:
            self.assertEqual(plan.plan_files([], "", 10), (set(), "", []))
            selected, _, _ = plan.plan_files([file()], "", 10)
        request.assert_not_called()
        self.assertEqual(selected, {"src/app.py"})

    def test_loader_called_once_no_env_changes_and_no_sample_expansion(self):
        files = [file(sample="中" * 5000)]
        loader = Mock(return_value=("项目文档", ["note"], {}))
        before = dict(os.environ)
        with self.request(return_value=result(files)) as request:
            plan.select_files("a" * 40, files, loader, input_bytes=10000)
        loader.assert_called_once_with("a" * 40, ["src/app.py"], max_bytes=plan.MAX_CONTEXT_BYTES)
        payload = json.loads(request.call_args.args[1][len(plan.INSTRUCTIONS):])
        self.assertLessEqual(len(payload["files"][0]["sample"].encode("utf-8")), 2000)
        self.assertEqual(payload["project_documents"], "项目文档")
        self.assertEqual(dict(os.environ), before)
        self.assertEqual(len(files[0]["sample"]), 5000)

    def test_loader_failure_is_advisory(self):
        files = [file()]
        with self.request(return_value=result(files)):
            selected, _, _ = plan.select_files("a" * 40, files,
                                               Mock(side_effect=ValueError("secret")))
        self.assertEqual(selected, {"src/app.py"})


if __name__ == "__main__":
    unittest.main()
